#!/usr/bin/env bash
# =============================================================================
# fw01-nft-apply.sh - Applies fw01 settings, then an nftables policy with
# automatic rollback (like `netplan try`)
#
# Also installs:
#   /etc/sysctl.d/90-fw01.conf            routing + kernel hardening
#   /etc/rsyslog.d/10-fw01-nftables.conf  firewall logs in a dedicated file
#   /etc/logrotate.d/fw01-nftables        rotation and retention of those logs
#
# Usage : sudo fw01-nft-apply.sh              menu: 1 routing only / 2 full filtering
#         sudo fw01-nft-apply.sh file.conf    applies that file directly
# Files : looked up in the admin's home folder (where scp drops them):
#         nftables-01-null.conf  routing + NAT, no filtering (lab build)
#         nftables-02-full.conf  full filtering by zone (production)
# How   : the new policy is loaded, then you have 120 s to type "ok".
#         Without confirmation (or if your SSH session drops), a systemd
#         timer restores the previous policy on its own.
# Log   : /var/log/fw01-nft-apply.log
# =============================================================================
set -euo pipefail

NEW_CONF="${1:-}"
CONF_DIR="${FW01_CONF_DIR:-$(getent passwd "${SUDO_USER:-root}" | cut -d: -f6)}"
DELAY=120
ROLLBACK="/root/nftables.rollback"
UNIT="fw01-nft-rollback"
LOG="/var/log/fw01-nft-apply.log"

# --- Display -----------------------------------------------------------------
G=$'\e[32m'; R=$'\e[31m'; B=$'\e[1m'; N=$'\e[0m'
phase() { printf '\n%s[%s/6] %s%s\n' "$B" "$1" "$2" "$N"; }
ok()    { printf '  %s✓%s %s\n' "$G" "$N" "$1"; }
ko()    { printf '  %s✗%s %s\n' "$R" "$N" "$1"; tail -n 15 "$LOG"; echo -e "\nFull log: $LOG"; exit 1; }
run()   { local label=$1; shift; echo "### $label" >>"$LOG"; if "$@" >>"$LOG" 2>&1; then ok "$label"; else ko "$label"; fi; }

# --- Prerequisites -------------------------------------------------------------
[[ $EUID -eq 0 ]]           || { echo "Run this script with sudo." >&2; exit 1; }
# No argument: menu to pick the policy
if [[ -z "$NEW_CONF" ]]; then
  echo "${B}Which policy to apply on fw01?${N}"
  echo "  1) Routing only : NAT to Internet, no filtering (lab build)"
  echo "  2) Full filtering: flows allowed per zone, everything else blocked (prod)"
  read -r -p "Choice [1/2]: " CHOICE
  case "$CHOICE" in
    1) NEW_CONF="${CONF_DIR}/nftables-01-null.conf" ;;
    2) NEW_CONF="${CONF_DIR}/nftables-02-full.conf" ;;
    *) echo "Invalid choice, nothing changed." >&2; exit 1 ;;
  esac
fi
[[ -f "$NEW_CONF" ]]        || { echo "File not found: ${NEW_CONF} (copy it with scp to ${CONF_DIR})" >&2; exit 1; }
: >"$LOG"; chmod 600 "$LOG"
echo "${B}fw01-nft-apply.sh${N} - ${NEW_CONF} - automatic rollback after ${DELAY} s"

# =============================================================================
# 1. Check: syntax validated before touching anything
# =============================================================================
phase 1 "Check"
run "syntax (nft -c)"                       nft -c -f "$NEW_CONF"

# =============================================================================
# 2. Kernel settings (sysctl)
#    ANSSI: no ICMP redirects or source routing, strict anti-spoofing
#    (rp_filter=1), martian packets logged.
#    systemd (50-default.conf) sets rp_filter=2 on every NIC through
#    "net.ipv4.conf.*": overridden with the same syntax, file 90 = read later.
# =============================================================================
sysctl_conf() {
  cat >/etc/sysctl.d/90-fw01.conf <<'EOF'
# /etc/sysctl.d/90-fw01.conf - generated by fw01-nft-apply.sh
# Routing between zones (fw01 is the lab router)
net.ipv4.ip_forward = 1
# Strict anti-spoofing: a packet must arrive on the NIC of its return route
net.ipv4.conf.all.rp_filter = 1
net.ipv4.conf.default.rp_filter = 1
net.ipv4.conf.*.rp_filter = 1
# No ICMP redirects (neither accepted nor sent)
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.default.accept_redirects = 0
net.ipv4.conf.all.secure_redirects = 0
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.default.send_redirects = 0
# No source routing
net.ipv4.conf.all.accept_source_route = 0
net.ipv4.conf.default.accept_source_route = 0
# Log packets with impossible addresses
net.ipv4.conf.all.log_martians = 1
net.ipv4.conf.default.log_martians = 1
# Ignore broadcast pings and bogus ICMP error responses
net.ipv4.icmp_echo_ignore_broadcasts = 1
net.ipv4.icmp_ignore_bogus_error_responses = 1
# SYN flood protection
net.ipv4.tcp_syncookies = 1
EOF
  chmod 644 /etc/sysctl.d/90-fw01.conf
  sysctl --system
}
phase 2 "Kernel settings"
run "/etc/sysctl.d/90-fw01.conf written and loaded"     sysctl_conf
run "check: ip_forward = 1"                          bash -c '[ "$(sysctl -n net.ipv4.ip_forward)" = 1 ]'
run "check: rp_filter = 1 on every NIC"     bash -c '! grep -qv "^1$" /proc/sys/net/ipv4/conf/*/rp_filter'

# =============================================================================
# 3. Firewall logging
#    ANSSI: log allowed and rejected flows, keep them locally.
#    nftables rules use a "fw01-..." prefix: rsyslog sends those lines to
#    /var/log/fw01-nftables.log, logrotate keeps 90 days.
# =============================================================================
logs_conf() {
  cat >/etc/rsyslog.d/10-fw01-nftables.conf <<'EOF'
# /etc/rsyslog.d/10-fw01-nftables.conf - generated by fw01-nft-apply.sh
# Firewall logs ("fw01-" prefix) in a dedicated local file
:msg, contains, "fw01-" -/var/log/fw01-nftables.log
& stop
EOF
  cat >/etc/logrotate.d/fw01-nftables <<'EOF'
# /etc/logrotate.d/fw01-nftables - generated by fw01-nft-apply.sh
# Daily rotation, 90 days kept, 100 MB max per file
/var/log/fw01-nftables.log {
    # /var/log is root:syslog 775: logrotate needs to be told which account
    # to run as (same setting as /etc/logrotate.d/rsyslog)
    su root syslog
    daily
    rotate 90
    maxsize 100M
    compress
    delaycompress
    missingok
    notifempty
    create 0640 syslog adm
    postrotate
        /usr/lib/rsyslog/rsyslog-rotate
    endscript
}
EOF
  chmod 644 /etc/rsyslog.d/10-fw01-nftables.conf /etc/logrotate.d/fw01-nftables
}
phase 3 "Logging"
run "rsyslog + logrotate written"                      logs_conf
run "check: rsyslog syntax (rsyslogd -N1)"          rsyslogd -N1
run "rsyslog restarted"                               systemctl restart rsyslog
run "check: logrotate syntax (logrotate -d)"        logrotate -d /etc/logrotate.d/fw01-nftables

# =============================================================================
# 4. Backup of the current policy (in memory and on disk)
# =============================================================================
save() {
  { echo "flush ruleset"; nft list ruleset; } >"$ROLLBACK"
  chmod 600 "$ROLLBACK"
  cp -a /etc/nftables.conf "/etc/nftables.conf.bak-$(date +%Y%m%d-%H%M%S)"
}
phase 4 "Backup"
run "current policy -> ${ROLLBACK} + /etc/nftables.conf.bak-*"   save

# =============================================================================
# 5. Apply with a safety net
#    The systemd timer runs outside your session: if SSH drops, the script
#    dies, but the rollback still happens.
# =============================================================================
arm()   { systemctl stop "${UNIT}.timer" 2>/dev/null || true
          systemd-run --quiet --unit="$UNIT" --on-active="$DELAY" /usr/sbin/nft -f "$ROLLBACK"; }
phase 5 "Apply"
run "rollback scheduled in ${DELAY} s"   arm
run "new policy loaded"                 nft -f "$NEW_CONF"

echo -e "\n  Test now from a ${B}2nd window${N}: ssh fw01, curl from web01..."
echo "  Connections already open (like this one) stay up (ct state established)."
read -r -t "$DELAY" -p "  Type ok to keep the new policy: " ANSWER || ANSWER=""
if [[ "$ANSWER" != "ok" ]]; then
  systemctl stop "${UNIT}.timer" 2>/dev/null || true
  nft -f "$ROLLBACK"
  printf '\n  %s✗%s no confirmation: previous policy restored.\n' "$R" "$N"
  exit 1
fi

# =============================================================================
# 6. Commit: cancel the rollback and make the policy persistent
# =============================================================================
persist() {
  systemctl stop "${UNIT}.timer"
  # same file (re-applying /etc/nftables.conf): install would refuse, nothing to copy
  [ "$(realpath "$NEW_CONF")" = /etc/nftables.conf ] || install -m 755 "$NEW_CONF" /etc/nftables.conf
  systemctl enable nftables
}
phase 6 "Commit"
run "rollback cancelled, /etc/nftables.conf replaced"   persist
run "check: nftables enabled at boot"                  systemctl is-enabled --quiet nftables
# Only when the policy filters (a NAT-only config stays in policy accept)
if grep -q 'policy drop' "$NEW_CONF"; then
  run "check: forward chain policy drop"              bash -c "nft list ruleset | grep -q 'hook forward priority filter; policy drop'"
fi

run "check: firewall logs in /var/log/fw01-nftables.log"  bash -c 'logger -p kern.info "fw01-test logging"; sleep 1; grep -q "fw01-test" /var/log/fw01-nftables.log'

echo -e "\n${G}${B}fw01 configured.${N} Script log: ${LOG} - Previous policy: /etc/nftables.conf.bak-*"
echo    "Firewall logs: sudo tail -f /var/log/fw01-nftables.log"
